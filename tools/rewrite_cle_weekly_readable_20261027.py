def enhance_sections(text, period):
    for anchor, note in READING_NOTES[period].items():
        start = text.index(f'<a id="{anchor}"></a>')
        next_anchor = text.find('<a id="a', start + 5)
        end = len(text) if next_anchor < 0 else next_anchor
        section = text[start:end]
        marker = '#### 1. 实验思路' if '#### 1. 实验思路' in section else '#### 1. 复核思路'
        assert marker in section, anchor
        thought = re.search(r'(?s)' + re.escape(marker) + r'\n\n(.*?)(?=\n\n#### 2\.)', section)
        assert thought, anchor
        section = section.replace(thought.group(0), '#### 为什么做这项实验\n\n' + COMBINED_NOTES[period][anchor], 1)
        for old, new in [('#### 2. 实验步骤', '#### 怎样做'), ('#### 2. 复核步骤', '#### 怎样做'),
                         ('#### 3. 实验结果', '#### 看到了什么'), ('#### 3. 复核结果', '#### 看到了什么'),
                         ('#### 4. 实验分析', '#### 这些结果说明什么'), ('#### 4. 复核分析', '#### 这些结果说明什么')]:
            section = section.replace(old, new)
        if period == '20261022' and anchor in GROUP_TABLES:
            section = section.replace('#### 怎样做', GROUP_TABLES[anchor] + '\n#### 怎样做', 1)
        if period == '20261014' and anchor == 'a2':
            section = section.replace('#### 怎样做', GROUP_TABLES['a2'] + '\n#### 怎样做', 1)
        text = text[:start] + section + text[end:]
    return text


